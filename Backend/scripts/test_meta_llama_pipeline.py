def display_llama_results(result: dict):
    print("\n" + "=" * 80)
    print("📋 [STEP 2] META LLAMA CLINICAL STRUCTURING & VERNACULAR RESULTS")
    print("=" * 80)

    doc = result["doctor_summary"]
    print(f"\n🏥 Clinic/Hospital: {doc['clinic_name']}")
    print(f"👨‍⚕️ Prescribing Doctor: {doc['doctor_name']}")
    print(f"🩺 Clinical Diagnosis: {doc['diagnosis']}")

    print("\n" + "-" * 80)
    print(f"💊 EXTRACTED MEDICATIONS & VERNACULAR GUIDANCE ({len(result['medications'])} items):")
    print("-" * 80)

    for i, med in enumerate(result["medications"], 1):
        sched = med["schedule"]
        icons = []
        if sched["morning"]: icons.append("☀️ Morning")
        if sched["afternoon"]: icons.append("🌤️ Noon")
        if sched["night"]: icons.append("🌙 Night")
        icon_str = " + ".join(icons) if icons else "🚨 SOS (As Needed)"

        print(f"\n[{i}] {med['medicine_name']} ({med['molecule']})")
        print(f"    • Schedule: {icon_str} | Food: {med['food_relation'].replace('_', ' ').title()}")
        print(f"    • Hindi Audio Script: \"{med['vernacular_instructions']['hi']}\"")
        print(f"    • Kannada Script:     \"{med['vernacular_instructions']['kn']}\"")
        print(f"    • Precaution:         {med['precautions']}")
        print(f"    • Confidence:         {med['confidence_score'] * 100:.1f}% (Verified Safe)")

    safety = result["responsible_ai_safety"]
    print("\n" + "=" * 80)
    print("🛡️ [STEP 3] RESPONSIBLE AI GUARDRAIL AUDIT (JURY EVALUATION PILLAR)")
    print("=" * 80)
    print(f"    • Contraindication Detected: {safety['contraindication_flag']}")
    print(f"    • Clinical Triage Level:     {safety['triage_level'].upper()}")
    print(f"    • Safety Advisory Note:      {safety['warning_message']}")
    print("=" * 80 + "\n")

