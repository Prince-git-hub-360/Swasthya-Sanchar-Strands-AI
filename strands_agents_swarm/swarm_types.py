"""
strands_agents_swarm.types

Domain types, dataclasses, and shared memory structures for the
Swasthya Sanchar AI 4-Agent Swarm (Strands Agents SDK).
"""

from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional
from datetime import datetime


@dataclass
class RawOcrToken:
    """Individual text token extracted by RxVisionAgent."""
    text: str
    confidence: float
    line_number: int


@dataclass
class VisionExtractionResult:
    """Output from RxVisionAgent."""
    raw_text: str
    tokens: List[RawOcrToken] = field(default_factory=list)
    detected_doctor_name: Optional[str] = None
    detected_clinic_name: Optional[str] = None
    image_quality_score: float = 1.0
    extracted_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


@dataclass
class PrescribedDrug:
    """Single clinical drug entity parsed by RxPharmacologyAgent."""
    brand_name: str
    generic_name: str
    dosage: str                      # e.g., "650mg", "500mg"
    frequency: str                   # e.g., "1-0-1", "BD", "OD", "TDS"
    frequency_expanded: str          # e.g., "Twice daily after meals"
    duration_days: int               # e.g., 5
    food_relation: str               # "after_meals" | "before_meals" | "with_meals"
    visual_pill_color: str           # e.g., "blue", "yellow", "white"
    purpose: str                     # e.g., "Fever & Pain relief", "Blood sugar management"


@dataclass
class PharmacologyRegimen:
    """Structured regimen and 5-day pillbox generated by RxPharmacologyAgent."""
    patient_id: str
    patient_name: str
    drugs: List[PrescribedDrug] = field(default_factory=list)
    pillbox_5day_matrix: Dict[str, Any] = field(default_factory=dict)
    clinical_notes: str = ""
    parsed_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


@dataclass
class SafetyAuditResult:
    """Clinical safety check and risk audit produced by RxSafetySentinel."""
    is_safe: bool
    risk_level: str                  # "SAFE" | "MODERATE_WARNING" | "CRITICAL_HAZARD"
    drug_interactions: List[str] = field(default_factory=list)
    dosage_threshold_warnings: List[str] = field(default_factory=list)
    food_contraindications: List[str] = field(default_factory=list)
    emergency_sos_triggered: bool = False
    emergency_reason: Optional[str] = None
    sentinel_verdict: str = ""
    audited_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


@dataclass
class VernacularStepInstruction:
    """Single dosage step translated for low-literacy visual display."""
    time_of_day: str                 # "Morning", "Afternoon", "Night"
    time_icon: str                   # "🌅", "☀️", "🌙"
    spoken_instruction: str          # Spoken vernacular string
    visual_pill_cue: str             # e.g., "1 Yellow Tablet"


@dataclass
class VernacularGuidance:
    """Patient-centric cultural & multilingual guidance by RxVernacularCommunicator."""
    target_language: str             # "hi", "te", "ta", "kn", "bn", etc.
    language_display_name: str       # "Hindi (हिंदी)", "Telugu (తెలుగు)", etc.
    full_spoken_script: str
    steps: List[VernacularStepInstruction] = field(default_factory=list)
    emergency_caregiver_advisory: Optional[str] = None
    generated_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


@dataclass
class SwarmExecutionReport:
    """Comprehensive end-to-end audit report of the 4-agent swarm pipeline."""
    execution_id: str
    input_source: str
    target_language: str
    vision: Optional[VisionExtractionResult] = None
    pharmacology: Optional[PharmacologyRegimen] = None
    safety: Optional[SafetyAuditResult] = None
    vernacular: Optional[VernacularGuidance] = None
    swarm_status: str = "INITIALIZED"  # "SUCCESS" | "GUARDRAIL_BLOCKED" | "SOS_ESCALATED"
    audit_trail: List[Dict[str, Any]] = field(default_factory=list)
    duration_ms: float = 0.0

